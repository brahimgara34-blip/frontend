// دالة حساب الأسعار التراكمية الرسمية للمتجر
export const calculateOfferPrice = (quantity: number): number => {
  if (quantity <= 1) return 199;
  if (quantity === 2) return 299;
  if (quantity === 3) return 399;
  return 399 + (quantity - 3) * 100;
};

export const calculateKneeReliefPrice = (quantity: number): number => {
  if (quantity <= 1) return 249;
  if (quantity === 2) return 379;
  if (quantity === 3) return 499;
  return 499 + (quantity - 3) * 150;
};
